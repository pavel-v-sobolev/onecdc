"""
Шаблон конфига: здесь собирается всё — подключения, параметры цикла, обработчики и расписания.

Запускается как обычный скрипт: `python runner.py`. Пакет handlers/ лежит рядом — Python кладёт
каталог скрипта в sys.path, поэтому импорт его находит. В контейнере этот каталог монтируется
в /config, и файл исполняется тем же способом, без единой правки путей.

Как есть файл уже работает: поднимается репликатор, читает изменения и пишет их в целевую БД.
Обработчики витрин и полные выгрузки по расписанию — ПРИМЕРЫ: их достаточно внести в списки
HANDLERS и CRON_JOBS ниже. Размер пула потоков и пула соединений считаются от длины этих списков,
поэтому помнить о них не нужно. Обработчики в handlers/ рядом — тоже примеры; пользовательская
сторона обработчиков описана в README_API.md, механика — в DESIGN.md.

Параметры присваиваются явно, по одному, чтобы на этом экране было видно, что именно передано в
репликатор. Значения взяты из окружения (удобно для контейнера), но любое можно заменить литералом:

    odata_url="http://server/base/odata/standard.odata",
    odata_auth=("odata", "secret"),   # None, если 1С опубликована без авторизации

На каждого обработчика — свой HandlerLoop со своим циклом, поэтому тяжёлая витрина не задерживает
остальные. Порядок между ними при этом не определён — на «витрина поверх витрины считается после
базовой» полагаться нельзя.

Репликатор обработчиков не запускает и о них не знает: сигналы идут через таблицу handlers.
Здесь они просто живут в одном процессе с ним — так проще. Отсюда и другие раскладки, каждая
правкой этого файла: разнести по контейнерам — убрать репликатор, останутся одни циклы обработчиков;
несколько планов обмена — завести второй Replicator и добавить его run_forever в RUNNABLES;
только полные выгрузки без чтения изменений — собрать Replicator (он исполнитель full_load:
метаданные, пагинация, запись, журнал) и просто не запускать его цикл. В самих обработчиках при
этом не меняется ничего.

Запускаются все одинаково: у репликатора, у обработчика и у расписания блокирующий run_forever,
и все они уходят в пул потоков. Останавливает всех SIGTERM.

ONECDC_MODE этот файл НЕ читает: смонтированный runner сам решает, что и как запускать, — он и
есть режим. Переменная действует только на раскладку без runner.py, где образ запускает `onecdc`.
"""

import logging
import os
from concurrent.futures import ThreadPoolExecutor
from functools import partial
# Нужен расписаниям (FullLoadCron ниже), когда грузится не весь объект, а свежий хвост.
# from datetime import timedelta

from sqlalchemy import create_engine

from onecdc import FullLoadCron, HandlerLoop, Replicator

# from handlers import ZakazyKlientov, ZakazyKlientovGrouped

# --- Что считаем и что выгружаем по расписанию ---------------------------------------------------

# Обработчики витрин: ПРИМЕР, замените на свои. Считают витрины из уже загруженных таблиц, каждый
# своим циклом. Классы — в handlers/ рядом.
HANDLERS = [
    # ZakazyKlientov(),
    # ZakazyKlientovGrouped(),
]

# Полные выгрузки по расписанию: ПРИМЕР, замените на свои.
#
# Зачем это нужно. Цикл изменений догоняет данные событиями, а полная выгрузка — сверяет: она читает
# объект из 1С и возвращает число РЕАЛЬНО изменённых строк, то есть при исправном CDC отвечает нулём.
# Ночная перегрузка свежего хвоста (последние сутки-двое) стоит недорого, а расхождение показывает
# сразу — и тут же его выравнивает.
#
# Имена — те, что видны в БД (латиница), как и у обработчиков: настраивая выгрузку, смотрят в базу
# и в реестр onecdc_metadata_objects (колонки object_full_name_en / fields_en). Оригинальные имена
# 1С ("Document_ЗаказКлиента") тоже принимаются. Расписание — обычная crontab-строка, время
# локальное: в контейнере задавайте TZ.
#
# Граница timedelta считается в момент срабатывания, поэтому окно едет вместе с процессом. Фильтр
# по периоду заодно делает выгрузку устойчивее: документы листаются через $skip, и выборка за пару
# прошедших суток, в отличие от всего объекта, почти не меняется под ногами.
CRON_JOBS = [
    # Каждую ночь в 03:00 — хвост за трое суток по документу, где важна свежесть.
    # dict(table_name="Document_ZakazKlienta", cron="0 3 * * *",
    #      date_field="Date", date_from=timedelta(days=3)),
    #
    # По воскресеньям в 02:00 — справочник целиком: он маленький, границы не нужны вовсе.
    # dict(table_name="Catalog_Nomenklatura", cron="0 2 * * 0"),
]

# --- Параметры -----------------------------------------------------------------------------------

# Те же переменные, что понимает образ без runner.py (см. README_ENV.md): иначе настройка в
# docker-compose.yml выглядела бы действующей, ничего не меняя.
FULL_LOAD_WORKERS = int(os.environ.get("ONECDC_FULL_LOAD_WORKERS", "2"))
POLL_INTERVAL = float(os.environ.get("ONECDC_POLL_INTERVAL", "60"))
LOG_LEVEL = os.environ.get("ONECDC_LOG_LEVEL", "INFO").strip().upper() or "INFO"
# Объект, впервые пришедший в пакете изменений, репликатор сам ставит на полную выгрузку — иначе в
# БД попадёт только то, что менялось после подключения. Выключают, если первую загрузку вы
# инициируете сами: регистрацией всех изменений на стороне 1С (обработка onecdc.epf) или
# расписанием FullLoadCron. Помеченный объект фоновые воркеры выгрузят в любом случае.
AUTOMATIC_FULL_LOAD = os.environ.get("ONECDC_AUTOMATIC_FULL_LOAD", "true").strip().lower() \
    not in ("0", "false", "no", "off")

# Соединения, которые репликатор держит СВЕРХ потоков полной выгрузки: цикл чтения изменений и два
# потока отметки живости — реестр незавершённых merge и захват объекта под выгрузку.
REPLICATOR_CONNECTIONS = 3

# Пул соединений считается, а не подбирается на глаз: к соединениям репликатора добавляется по
# одному на каждый обработчик и каждое расписание — они работают своими потоками (подробнее в
# README_DB.md, «Сколько нужно соединений к БД»).
engine = create_engine(
    os.environ["ONECDC_DB_URL"],
    pool_size=FULL_LOAD_WORKERS + REPLICATOR_CONNECTIONS + len(HANDLERS) + len(CRON_JOBS),
)

DB_SCHEMA = os.environ.get("ONECDC_DB_SCHEMA")
# Куда класть одноразовые таблицы ключей полной выгрузки. Не обязательна (не задана — схема
# данных), но в отдельной схеме по определению нет ничего ценного: таблицу, оставшуюся после
# падения процесса, там видно и не жалко удалить. Промежуточную таблицу merge dbmerge заводит
# сам, настоящей TEMPORARY, и эта схема к ней отношения не имеет.
DB_TEMP_SCHEMA = os.environ.get("ONECDC_DB_TEMP_SCHEMA")

# Пользователь не задан — работаем без авторизации, как и образ без runner.py. Требовать здесь обе
# переменные значило бы, что одна и та же 1С без авторизации доступна из одной раскладки образа и
# недоступна из другой.
ODATA_USER = os.environ.get("ONECDC_ODATA_USER")

replicator = Replicator(
    odata_url=os.environ["ONECDC_ODATA_URL"],
    odata_auth=((ODATA_USER, os.environ.get("ONECDC_ODATA_PASSWORD", "")) if ODATA_USER else None),
    exchange_name=os.environ["ONECDC_EXCHANGE_NAME"],
    # Не знаете guid узла — оставьте пустым: в лог выведется список узлов плана обмена.
    queue_guid=os.environ.get("ONECDC_QUEUE_GUID", ""),
    engine=engine,
    db_schema=DB_SCHEMA,
    db_temp_schema=DB_TEMP_SCHEMA,
    full_load_workers=FULL_LOAD_WORKERS,
    automatic_full_load=AUTOMATIC_FULL_LOAD,
)

# Уровень — после конструктора: он вешает обработчик на логгер onecdc (по умолчанию INFO), а тут
# уровень переопределяется на заданный.
logging.getLogger("onecdc").setLevel(LOG_LEVEL)

# --- Запуск ---------------------------------------------------------------------------------------

# По потоку на каждый run_forever. Считаем от списка, а не помним число: единственный поток,
# занятый репликатором навсегда, оставил бы задания обработчиков в очереди пула — витрины не
# обновлялись бы, и ни одной ошибки при этом не появилось бы.
RUNNABLES = [partial(replicator.run_forever, interval=POLL_INTERVAL)]
RUNNABLES += [HandlerLoop(engine=engine, schema=DB_SCHEMA, handler=handler).run_forever
              for handler in HANDLERS]
RUNNABLES += [FullLoadCron(replicator, **job).run_forever for job in CRON_JOBS]

with ThreadPoolExecutor(max_workers=len(RUNNABLES), thread_name_prefix='cdc') as pool:
    tasks = [pool.submit(run) for run in RUNNABLES]
    for task in tasks:
        task.result()
